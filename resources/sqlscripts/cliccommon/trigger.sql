CREATE TRIGGER `TGR_AI_SUM_CREDIT_MONHTLY` AFTER INSERT ON `T_CK_CREDIT_JOURNAL` FOR EACH ROW replace into T_CK_CREDIT_SUMMARY_MONTH(CRSM_COMPANY, CRSM_MONTH, CRSM_SERVICE_TYPE, CRSM_AMT, CRSM_RESERVE, CRSM_UTILIZED, CRSM_BALANCE
, CRSM_CCY, CRSM_STATUS, CRSM_DT_CREATE, CRSM_UID_CREATE)
select CJN_COMPANY, date_format(CJN_DT_CREATE, '%Y%m'), CJN_SERVICE_TYPE, 0, sum(CJN_RESERVE), sum(CJN_UTILIZED), 0
, CJN_CCY, 'A', sysdate(), 'sys'
FROM T_CK_CREDIT_JOURNAL
where CJN_SERVICE_TYPE = NEW.CJN_SERVICE_TYPE AND CJN_COMPANY = NEW.CJN_COMPANY AND CJN_CCY = NEW.CJN_CCY
	and date_format(now(), '%Y%m') =date_format(CJN_DT_CREATE, '%Y%m')
	and CJN_COMPANY in (select ACCN_ID from T_CORE_ACCN)
group by CJN_SERVICE_TYPE, CJN_COMPANY, CJN_CCY, date_format(CJN_DT_CREATE, '%Y%m');

