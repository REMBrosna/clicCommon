-- TRIGGER TGR_AU_SUM_CREDIT ----------------------------------------------------------------------------
CREATE TRIGGER `TGR_AU_SUM_CREDIT` AFTER UPDATE ON `T_CK_CREDIT_JOURNAL` FOR EACH ROW UPDATE T_CK_CREDIT_SUMMARY,
(
	SELECT SUM(CJN_RESERVE) vReserved, SUM(CJN_UTILIZED) vUtillized
	FROM T_CK_CREDIT_JOURNAL
	WHERE CJN_COMPANY = OLD.CJN_COMPANY AND CJN_SERVICE_TYPE = OLD.CJN_SERVICE_TYPE AND CJN_CCY = OLD.CJN_CCY
) src
	SET 
	CRS_BALANCE =CRS_AMT - (vReserved + vUtillized), CRS_RESERVE = vReserved,	CRS_UTILIZED = vUtillized		
	WHERE CRS_SERVICE_TYPE = NEW.CJN_SERVICE_TYPE AND CRS_COMPANY = NEW.CJN_COMPANY AND CRS_CCY = NEW.CJN_CCY;

