

SELECT jt.* 
FROM clickargo2.T_CK_JOB_TRUCK jt, clickargo2.T_CK_PAYMENT_TXN pt
where pt.PTX_PAYMENT_STATE = 'PAID'
	AND PTX_TYPE ='BNKTF'
	and locate(jt.JOB_ID, pt.PTX_SVC_REF) > 0
    AND JOB_OUT_PAYMENT_STATE != 'PAID'  ;
    
