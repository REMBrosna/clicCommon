	private static Logger log = Logger.getLogger(JasperDocsUtil.class);

	/***
	 * Generate report for template with list. This is applicable for preview where
	 * the request to generate the PDF is initiated from the client.
	 * 
	 * @param request
	 * @param jrXmlString
	 * @param parameters
	 * @return
	 */
	public static byte[] createPDF(HttpServletRequest request, String jrXmlString, Map<String, Object> parameters) {
		ByteArrayOutputStream byteStream = null;
		try {
			JasperReport jasperReport = getReportTemplate(request, jrXmlString);

			JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, parameters, new JREmptyDataSource());

			byteStream = new ByteArrayOutputStream();
			JasperExportManager.exportReportToPdfStream(jasperPrint, byteStream);

		} catch (Exception e) {
			log.error("createPDF", e);
		} finally {
			try {
				if (null != byteStream) {
					byteStream.close();
				}
			} catch (Exception e) {
				log.error("createPDF", e);
			}
		}
		if (byteStream != null) {
			return byteStream.toByteArray();
		} else {
			return null;
		}
	}

