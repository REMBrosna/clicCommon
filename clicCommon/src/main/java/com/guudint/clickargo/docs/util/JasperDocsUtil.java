	/***
	 * Generate report for template without list.
	 * 
	 * @param request
	 * @param jrXmlString
	 * @param parameters
	 * @param dataSource
	 * @return
	 */
	public static byte[] createPDF(String basePath, List<String> jrXmlString, Map<String, Object> parameters,
			JRBeanCollectionDataSource dataSource) {

		ByteArrayOutputStream byteStream = null;
		List<JasperPrint> list = new ArrayList<JasperPrint>();
		JRPdfExporter exp = new JRPdfExporter();
		for (String jrxmlFile : jrXmlString) {

			try {

				JasperReport jasperReport = getReportTemplate(basePath, jrxmlFile);
				JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, parameters, dataSource);
				list.add(jasperPrint);
//				byteStream = new ByteArrayOutputStream();
//				JasperExportManager.exportReportToPdfStream(jasperPrint, byteStream);

			} catch (Exception e) {
				e.printStackTrace();
				log.error("createPDF", e);
			} finally {
				try {
					if (null != byteStream) {
						byteStream.close();
						byteStream.flush();
					}
				} catch (Exception ex) {
					ex.printStackTrace();
					log.error("createPDF", ex);
				}
			}
		}

		if (!list.isEmpty()) {
			try {
				byteStream = new ByteArrayOutputStream();
				exp.setExporterInput(SimpleExporterInput.getInstance(list));
				exp.setExporterOutput(new SimpleOutputStreamExporterOutput(byteStream));
				exp.exportReport();

			} catch (Exception ex) {
				ex.printStackTrace();
			}

		}

		if (byteStream != null) {
			return byteStream.toByteArray();
		} else {
			return null;
		}
	}

	/***
	 *
	 * @param fileName
	 * @return
	 */
	public static HttpHeaders getPDFHeader(String fileName) {
		HttpHeaders headers = new HttpHeaders();
		headers.setContentType(MediaType.parseMediaType("application/pdf"));
		StringBuilder builder = new StringBuilder("inline; filename=\"");
		builder.append(fileName).append('\"');
		headers.add("Content-Disposition", builder.toString());
		headers.setCacheControl("must-revalidate, post-check=0, pre-check=0");
		return headers;
	}

	/***
	 *
	 * @param request
	 * @param jrXmlString
	 * @return
	 * @throws Exception
	 */
	private static JasperReport getReportTemplate(HttpServletRequest request, String jrXmlString) throws Exception {
		return JasperCompileManager.compileReport(request.getSession().getServletContext().getRealPath(jrXmlString));
	}

	/***
	 *
	 * @param request
	 * @param jrXmlString
	 * @return
	 * @throws Exception
	 */
	private static JasperReport getReportTemplate(String basePath, String jrXmlString) throws Exception {
		return JasperCompileManager.compileReport(basePath.concat(jrXmlString));
	}

